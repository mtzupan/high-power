"""Convert turbine-reading CSVs into a data.js file for the Web Lab project.

Web Lab may not let students upload or fetch() CSV files, so the readings are
written out as plain JavaScript list literals instead.

Usage (from the repo root):
    python3 weblab/csv_to_datajs.py notebooks/datasets/IMG_8355_readings.csv
    python3 weblab/csv_to_datajs.py run_a.csv run_b.csv -o weblab/project/data.js

The first CSV becomes `readings`; every CSV is also available in `datasets`
under its file name (without .csv).
"""

import argparse
import csv
import json
from pathlib import Path

NUMBER_COLUMNS = ["time_s", "current_mA", "voltage_V", "Hz"]
DEFAULT_OUT = Path(__file__).parent / "project" / "data.js"


def js_number(text):
    # Blank cells (DMM overload, unreadable tachometer) become null in JS.
    # Numbers keep their CSV spelling so students see -0.00003, not -3e-05.
    text = (text or "").strip()
    if text == "":
        return "null"
    float(text)  # fail loudly on anything that isn't a number
    return text


def read_rows(csv_path):
    with open(csv_path, newline="") as file:
        return list(csv.DictReader(file))


def to_js_list(rows):
    lines = []
    for row in rows:
        fields = [f"{col}: {js_number(row.get(col))}" for col in NUMBER_COLUMNS]
        fields.append(f"notes: {json.dumps((row.get('notes') or '').strip())}")
        lines.append("  { " + ", ".join(fields) + " }")
    return "[\n" + ",\n".join(lines) + "\n]"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("csv_files", nargs="+", type=Path)
    parser.add_argument("-o", "--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    parts = [
        "// Generated by weblab/csv_to_datajs.py -- do not edit by hand.",
        "// Each reading has: time_s, current_mA, voltage_V, Hz, notes.",
        "// A value of null means the instrument could not be read at that second.",
        "",
        "const datasets = {};",
    ]
    for csv_path in args.csv_files:
        name = csv_path.stem
        parts.append("")
        parts.append(f"// Source: {csv_path.name}")
        parts.append(f"datasets[{json.dumps(name)}] = {to_js_list(read_rows(csv_path))};")

    first = json.dumps(args.csv_files[0].stem)
    parts += ["", f"const readings = datasets[{first}];", ""]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(parts))
    print(f"Wrote {args.out} ({len(args.csv_files)} dataset(s))")


if __name__ == "__main__":
    main()
